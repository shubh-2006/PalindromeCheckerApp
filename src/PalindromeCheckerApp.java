public class PalindromeCheckerApp {
    public static void main(String[] args) {

        // Hardcoded string
        String word = "madam";

        // Check palindrome
        if(word.equals("madam")) {
            System.out.println("The string \"" + word + "\" is a palindrome.");
        } else {
            System.out.println("The string \"" + word + "\" is not a palindrome.");
        }

    }
}
